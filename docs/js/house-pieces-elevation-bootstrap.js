(() => {
  'use strict';

  if (window.__hobunjiHouseElevationBootstrapInstalled) return;
  window.__hobunjiHouseElevationBootstrapInstalled = true;

  const housePieces = window.HousePieces;
  if (!housePieces) {
    console.warn('[PlayerHouseElevation] HousePieces core was not loaded before the elevation bootstrap.');
    return;
  }

  let deps = null; // Captured HousePieces.init dependencies; used to sync live farm terrain and locate generated house meshes.
  let controller = null; // PlayerHouseElevation controller for the active farm/world.
  let houseAssetUpgradePromise = null; // Shared brick/shingle readiness pass; rebuilds starter-house meshes once real assets replace placeholders.

  function _applyMeshElevation(mesh, y) {
    if (!mesh?.position) return;
    mesh.userData = mesh.userData || {};
    if (!Number.isFinite(mesh.userData.playerHouseElevationBaseY)) {
      mesh.userData.playerHouseElevationBaseY = Number(mesh.position.y) || 0;
    }
    mesh.position.y = mesh.userData.playerHouseElevationBaseY + y;
  }

  function _refreshHouseMeshElevation(extraGroups = []) {
    if (!deps || !controller) return;
    const y = controller.worldY();
    for (const entry of deps.getHousePieces?.() || []) _applyMeshElevation(entry?._mesh, y);
    for (const mesh of extraGroups) _applyMeshElevation(mesh, y);
  }

  function _newSceneGroups(before) {
    if (!deps?.scene || !before) return [];
    return deps.scene.children.filter(obj => !before.has(obj) && obj?.isGroup);
  }

  function _syncAfterMutation(before, force = false) {
    if (!controller) return;
    const newGroups = _newSceneGroups(before);
    controller.sync(force);
    _refreshHouseMeshElevation(newGroups);
  }

  // Auto-generated entrances are fallback topology, not authored obstacles.
  // Their exterior approach reservation occupies a tile in worldObjects,
  // which generic house placement validation would otherwise mistake for a
  // real blocker. Temporarily remove ONLY those generated reservations while
  // testing/committing a room footprint. The actual "Enter" interaction stays
  // on the wall/entry-tunnel tile. If the operation fails, put each untouched
  // reservation back; if it succeeds and rebuilds the house, the core throws
  // the old auto feature away and derives/registers a new free wall.
  function _autoEntranceDoorRecords() {
    const records = [];
    if (!deps?.worldObjects) return records;
    for (const entry of deps.getHousePieces?.() || []) {
      for (const feature of entry.features || []) {
        if (feature?.type !== 'entrance' || !feature.autoGenerated || !feature._approachObj || !feature._approachKey) continue;
        if (deps.worldObjects.get(feature._approachKey) !== feature._approachObj) continue;
        records.push({ feature, key: feature._approachKey, approachObj: feature._approachObj });
      }
    }
    return records;
  }

  function _withAutoEntrancePassThrough(run) {
    const records = _autoEntranceDoorRecords();
    for (const record of records) deps.worldObjects.delete(record.key);
    try {
      return run();
    } finally {
      for (const record of records) {
        // A successful built-room mutation causes the core reconciliation pass
        // to clear/replace this exact feature object. Only restore a marker if
        // it is still the live one and its tile stayed otherwise unoccupied.
        if (record.feature._approachObj !== record.approachObj) continue;
        if (!deps.worldObjects.has(record.key)) deps.worldObjects.set(record.key, record.approachObj);
      }
    }
  }

  // The starter house can be created before Roughbrick1.glb finishes loading.
  // In that case WallBuilder correctly supplies its brown placeholder, but
  // those already-created InstancedMeshes keep the placeholder material even
  // after the real GLB replaces the library entry. Town buildings solve the
  // same transition with a GLB-ready rebuild. Do the same here, while queuing
  // the exact same brick/shingle tint requests first so the rebuilt player
  // house shares the town texture treatment from its first settled frame.
  function _ensureTexturedHouseAssets() {
    if (!deps?.houseWallBuilder || typeof HousePieceGen === 'undefined') return;
    const wallBuilder = deps.houseWallBuilder;
    wallBuilder.tintDefaultGlb?.('assets/textures/carved_smooth.png', '#4d4d4d');
    HousePieceGen.tintShingleMaterial?.('assets/textures/carved_smooth.png', '#7d7355');
    if (houseAssetUpgradePromise) return;
    houseAssetUpgradePromise = Promise.all([
      wallBuilder.loadDefaultGlb?.() || Promise.resolve(),
      HousePieceGen.loadShingleGlb?.('assets/models/') || Promise.resolve(),
    ]).then(() => {
      // Re-issue after load as well; both APIs cache identical tint requests,
      // so this is cheap and also covers assets that were populated elsewhere.
      wallBuilder.tintDefaultGlb?.('assets/textures/carved_smooth.png', '#4d4d4d');
      HousePieceGen.tintShingleMaterial?.('assets/textures/carved_smooth.png', '#7d7355');
      // rebuildStructureMeshes is itself wrapped below, so this one public
      // call also performs the elevation resync for the replacement meshes.
      housePieces.rebuildStructureMeshes?.();
      deps.debugLog?.('Player house: upgraded starter meshes to textured brick/shingle assets.');
    }).catch(error => {
      houseAssetUpgradePromise = null;
      deps?.debugLog?.(`Player house asset upgrade failed: ${error?.message || error}`, 'warn');
    });
  }

  const originalInit = housePieces.init;
  housePieces.init = function (injectedDeps) {
    deps = injectedDeps;
    const result = originalInit.call(this, injectedDeps);
    try {
      controller?.dispose?.();
      controller = window.PlayerHouseElevation.create({
        cols: deps.COLS,
        rows: deps.ROWS,
        scene: deps.scene,
        getGrid: deps.getGrid,
        getPieces: deps.getHousePieces,
        markTileDirty: deps.markTileDirty,
        recomputeWater: deps.recomputeWater,
        debugLog: deps.debugLog,
      });
      controller.sync(true);
      _refreshHouseMeshElevation();
    } catch (error) {
      controller = null;
      deps.debugLog?.(`Player house subtle elevation unavailable: ${error?.message || error}`, 'warn');
    }
    _ensureTexturedHouseAssets();
    return result;
  };

  // Restore the architectural rule that an AUTO entrance can be swallowed by
  // a new/moved/rotated room. Manual entrances intentionally remain normal
  // blockers until the player relocates/removes them. canPlaceAt and
  // canMovePieceTo are wrapped too so the House Layout editor's live preview
  // agrees with the eventual commit operation.
  const autoEntrancePassThroughOperations = [
    'canPlaceAt', 'canMovePieceTo', 'placeDeed', 'movePiece', 'rotatePiece',
  ];
  for (const name of autoEntrancePassThroughOperations) {
    const original = housePieces[name];
    if (typeof original !== 'function') continue;
    housePieces[name] = function (...args) {
      return _withAutoEntrancePassThrough(() => original.apply(this, args));
    };
  }

  // HousePieces' internal mutation methods call private rebuild helpers, so
  // wrapping the public operation boundary is the least-coupled place to
  // recalculate the modular footprint and lift whatever meshes that rebuild
  // created. Roof/feature-only rebuilds hit controller.sync() too, but its
  // footprint fingerprint makes those terrain passes no-ops.
  const wrappedOperations = [
    'spawnEntry', 'seedStarter', 'placeDeed', 'build', 'demolish',
    'moveHouse', 'movePiece', 'rotatePiece', 'rotateRoofAxis',
    'placeFeature', 'removeFeatureAt', 'rebuildStructureMeshes', 'clearAll',
  ];
  for (const name of wrappedOperations) {
    const original = housePieces[name];
    if (typeof original !== 'function') continue;
    housePieces[name] = function (...args) {
      const before = deps?.scene ? new Set(deps.scene.children) : null;
      const result = original.apply(this, args);
      _syncAfterMutation(before);
      return result;
    };
  }

  function debugHouseElevation() {
    return controller?.debugSnapshot?.() || {
      footprintCells: 0,
      affectedCenters: 0,
      deformedTileCells: 0,
      worldY: 0,
      status: controller ? 'ready' : 'not-initialized',
    };
  }

  housePieces.debugHouseElevation = debugHouseElevation;
  window.__hobunjiHouseElevationDebug = debugHouseElevation;
})();
