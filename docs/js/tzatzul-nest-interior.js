// Tzatzul nest interiors use the normal cave locale/carver and carved-rock scene.
// This adapter only supplies the authored boss arena's raised rock perches,
// physical obstacle tiles, and the Furniture Author's sharp stone clusters.
(() => {
  'use strict';
  if (window.TzatzulNestInterior) return;
  const PREFIX = 'map_i_den_tzatzul_'; // Stable cave locale IDs are generated by the exterior spire planner.
  const records = new Map(); // Map ID -> small encounter plan, current carved mesh and reusable perch supports.
  const diagnostics = { builds: 0, geometryBuilds: 0, spikeMeshes: 0, rockMeshes: 0,
    missingCoverage: 0, lastError: null }; // Mobile-visible counters; no additional scene traversal or frame loop.
  const validId = id => /^map_i_den_tzatzul_map_(?:northern_cliffs|western_slope)_[01]$/.test(String(id || ''));
  const finite = (v, fallback = 0) => Number.isFinite(Number(v)) ? Number(v) : fallback;
  function features(mapData) {
    if (!validId(mapData?.id)) return null;
    const data = mapData.cavernFeatures?.tzatzulNest;
    return data && Array.isArray(data.wallPerches) && Array.isArray(data.stoneSpikeClusters) ? data : null;
  }
  function decorateData(mapData) {
    const plan = features(mapData);
    if (!plan) return mapData;
    // Existing interior tile collision consumes the same mapData.colliders as
    // other caverns. The sharpness of a spike is separately authored on the
    // generated mesh rather than treating every stone wall as bladed.
    const colliders = new Map((mapData.colliders || []).filter(Array.isArray)
      .map(tile => [tile.join(','), tile])); // Avoid duplicate obstacle cells across carve re-entry.
    const floor = new Set((mapData.floor || []).map(tile => tile.join(','))); // Never author a solid collider off the carved ground.
    for (const rock of [...plan.wallPerches, ...plan.stoneSpikeClusters]) {
      const col = Math.floor(finite(rock.col)), row = Math.floor(finite(rock.row));
      const key = col + ',' + row;
      if (floor.has(key)) colliders.set(key, [col, row]);
    }
    mapData.colliders = [...colliders.values()];
    mapData.entrySpots ||= {};
    mapData.entrySpots.tzatzul_delivery = { col: finite(plan.arenaCenter?.col, 13), row: finite(plan.arenaCenter?.row, 13) + 1 }; // Abduction arrives inside the arena, clear of the automatic exit tile.
    const record = records.get(mapData.id) || { mesh: null, group: null, registered: false, points: [] };
    record.plan = plan; record.floorY = finite(mapData.floorSurfaceY);
    record.mapId = mapData.id;
    records.set(mapData.id, record);
    diagnostics.builds++;
    return mapData;
  }
  function disposeOwned(record) {
    if (!record?.group) return;
    record.group.parent?.remove?.(record.group);
    record.group.traverse?.(node => {
      if (!node.isMesh) return;
      if (!node.userData?.tzatzulSharedRockMaterial) node.material?.dispose?.();
      node.geometry?.dispose?.();
    }); // Only meshes constructed by this owner; never dispose the cave shell's shared material.
    record.group = null; record.mesh = null;
  }
  function draw(THREE, meshData, caveMesh) {
    const mapId = String(meshData?.caveGrowthSeed || '');
    const record = records.get(mapId);
    if (!record || !caveMesh?.add || !THREE?.CylinderGeometry) return caveMesh;
    if (record.mesh !== caveMesh) disposeOwned(record);
    if (record.group?.parent === caveMesh) return caveMesh; // A cached interior must not duplicate geometry.
    const plan = record.plan, group = new THREE.Group();
    const stretch = window.HobunjiSurfaceStretchUV; // Same connected-surface stretch-to-fit PNG mapping used by Banubu's carved cave.
    group.name = 'tzatzul-nest-arena:' + mapId;
    group.userData.tzatzulArena = { mapId, rockyPerches: plan.wallPerches.length,
      stoneSpikeClusters: plan.stoneSpikeClusters.length };
    record.points = [];
    for (const ledge of plan.wallPerches) {
      const height = Math.max(1.5, finite(ledge.height, 3));
      const rock = new THREE.Mesh(new THREE.CylinderGeometry(.7, .93, height, 7, 2), caveMesh.material);
      rock.name = 'tzatzul-stone-wall-perch:' + ledge.id;
      rock.position.set(finite(ledge.col) + .5, record.floorY + height / 2, finite(ledge.row) + .5);
      stretch?.mapMesh?.(rock, { label: 'interior-cavern:tzatzul-rock-perch', maxPatchWorldSize: 6 }); // Texture the top cap and walls, not just the curved side.
       rock.userData.tzatzulSharedRockMaterial = true;
      rock.userData.tzatzulRockPerch = true; // 1D/0D support is registered on demand when the area becomes active.
      group.add(rock);
      record.points.push({ id: mapId + ':' + ledge.id, col: ledge.col, row: ledge.row,
        worldY: record.floorY + height });
      diagnostics.rockMeshes++;
    }
    for (const spike of plan.stoneSpikeClusters) {
      // This is the Furniture Author's *real* stone-stalagmite generator, not
      // substitute cones. The seed box is an invisible authored furniture
      // support, with the 9-sliced shell outlines supplied by the generator.
      const seed = new THREE.Group(), part = new THREE.Mesh(
        new THREE.BoxGeometry(Math.max(.4, finite(spike.width, 1)), .12, Math.max(.4, finite(spike.width, 1))),
        new THREE.MeshBasicMaterial({ visible: false })
      );
      part.position.y = .06;
      part.visible = false;
      part.userData.authoredPartId = 'tzatzul-spike-seed';
      seed.add(part);
      const generator = window.IceStalagmiteCoverage?.build;
      if (typeof generator === 'function') {
        const layer = generator(THREE, seed, {
          kind: 'stoneStalagmites', target: 'selected', targetIds: ['tzatzul-spike-seed'],
          seed: mapId + ':' + spike.id, color: '#77736e', count: 4,
          density: Math.max(1, Math.min(6, finite(spike.density, 12) / 4)), radius: .14,
          iceHeightMin: .35, iceHeightMax: 1.2, iceCluster: 3, iceEngulf: .78,
          iceFootprintPadding: .07, iceFacets: 6, iceTipSharpness: .95,
          iceLean: .09, iceRoughness: .45, iceOpacity: 1,
        });
        layer.name = 'tzatzul-sharp-stone:' + spike.id;
        layer.position.set(finite(spike.col) + .5, record.floorY, finite(spike.row) + .5);
        layer.userData.tzatzulSpikeCollisionTile = [spike.col, spike.row];
        group.add(layer);
        diagnostics.spikeMeshes++;
      } else diagnostics.missingCoverage++;
      part.geometry.dispose(); part.material.dispose(); // The generated facets own their own cloned vertex buffers.
    }
    caveMesh.add(group);
    record.mesh = caveMesh; record.group = group;
    diagnostics.geometryBuilds++;
    return caveMesh;
  }
  function supportsFor(mapId, tileSize = 64) {
    const record = records.get(String(mapId));
    if (!record?.points?.length) return [];
    const size = Math.max(1, finite(tileSize, 64)); // Same world tile unit that creature branch/perch positions use.
    return record.points.map(ledge => window.PerchSupport?.point?.(
      ledge.id, (ledge.col + .5) * size, (ledge.row + .5) * size, ledge.worldY
    )).filter(Boolean);
  }
  function ensurePerches(mapId, tileSize = 64) {
    const record = records.get(String(mapId));
    if (!record?.points?.length || !window.PerchSupport?.register) return [];
    const points = supportsFor(mapId, tileSize);
    for (const point of points) window.PerchSupport.register(mapId, point);
    record.registered = true;
    return points;
  }
  function releaseInactive(activeId) {
    for (const [id, record] of records) {
      if (id === activeId || !record.registered) continue;
      for (const point of record.points) window.PerchSupport?.unregister?.(id, point.id);
      record.registered = false; // Keep cached cavern geometry; it will display without a rebuild on return.
    }
  }
  function debugSnapshot() {
    return { ...diagnostics, arenas: [...records].map(([id,r]) => ({
      id, perches:r.points?.length || 0, rendered:!!r.group, registered:!!r.registered,
      mother:r.plan?.mother?.kind || null, hatchlings:r.plan?.hatchlings?.length || 0,
      stoneClusters:r.plan?.stoneSpikeClusters?.length || 0,
    })) };
  }
  function install() {
    const caverns = window.CavernGenerator, scene = window.InteriorSceneBuilder;
    if (!caverns?.synthesizeLocaleCavernMapData || !scene?.buildCarvedCavernMesh) return false;
    if (!caverns.__tzatzulNestWrapped) {
      const original = caverns.synthesizeLocaleCavernMapData;
      caverns.synthesizeLocaleCavernMapData = function (...args) {
        return decorateData(original.apply(this,args));
      };
      caverns.__tzatzulNestWrapped = true;
    }
    if (!scene.__tzatzulNestWrapped) {
      const original = scene.buildCarvedCavernMesh;
      scene.buildCarvedCavernMesh = function (...args) {
        const mesh = original.apply(this,args); // Retain the native floor/wall mesh ownership and material mapping.
        try { return draw(args[0], args[1], mesh); }
        catch (error) { diagnostics.lastError = String(error); return mesh; } // Never block ordinary interior loading on optional rocks.
      };
      scene.__tzatzulNestWrapped = true;
    }
    return true;
  }
  window.TzatzulNestInterior = Object.freeze({
    install, isNestMap: validId, decorateData, draw, ensurePerches, supportsFor,
    releaseInactive, getArena: id => records.get(String(id))?.plan || null,
    getFloorY: id => finite(records.get(String(id))?.floorY), // Return the real carved elevation for rock and sharp-stone collision.
    debugSnapshot,
  });
  install(); // Both shared builders are already loaded by index.html, before game.js.
})();
