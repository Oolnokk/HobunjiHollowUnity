'use strict';

// Behavioral tests for the central tile signal and the existing chunk frame owner.
const assert = require('assert');
const fs = require('fs');
const vm = require('vm');

let now = 0; // Controls backoff expiry and rendering timestamps in the simulated game loop.
const listenerErrors = []; // Captures isolated subscriber failures without noisy CI output.
class Group {
  constructor() { this.children = []; this.parent = null; this.userData = {}; this.name = ''; }
  add(child) { this.children.push(child); child.parent = this; }
  remove(child) { this.children = this.children.filter(item => item !== child); child.parent = null; }
  clear() { for (const child of this.children) child.parent = null; this.children.length = 0; }
  traverse(visitor) { visitor(this); for (const child of this.children) child.traverse?.(visitor); }
}
const ctx = {
  console: { error: (...args) => listenerErrors.push(args), log: console.log },
  performance: { now: () => now },
  document: { getElementById: () => null },
  navigator: { deviceMemory: 4 },
  matchMedia: () => ({ matches: true }),
  THREE: { Group },
};
ctx.window = ctx;
vm.createContext(ctx);
vm.runInContext(fs.readFileSync('docs/js/player-tile-events.js', 'utf8'), ctx);
vm.runInContext(fs.readFileSync('docs/js/wilderness-chunks.js', 'utf8'), ctx);

const events = []; // Records the exact notifications generated by spatial changes.
const unsubscribe = ctx.PlayerTileEvents.subscribe(event => events.push(event));
const unsubscribeFailing = ctx.PlayerTileEvents.subscribe(() => { throw new Error('isolated consumer failure'); });
assert.strictEqual(ctx.PlayerTileEvents.update('zone', 16, 16, 16), true);
assert.strictEqual(events[0].reason, 'initial');
assert.strictEqual(events[0].from, null);
assert.strictEqual(events[0].to.col, 1);
assert.ok(Object.isFrozen(events[0]) && Object.isFrozen(events[0].to), 'events and coordinates cannot be mutated by subscribers');
assert.strictEqual(ctx.PlayerTileEvents.update('zone', 31, 31, 16), false, 'movement inside the same tile does not allocate/emit');
assert.strictEqual(ctx.PlayerTileEvents.update('zone', 32, 31, 16), true);
assert.strictEqual(events[1].reason, 'tile');
assert.strictEqual(events[1].from.col, 1);
assert.strictEqual(events[1].to.col, 2);
assert.strictEqual(ctx.PlayerTileEvents.update('zone', -0.1, -16.1, 16), true);
assert.strictEqual(events[2].to.col, -1, 'negative coordinates floor rather than truncate');
assert.strictEqual(events[2].to.row, -2);
assert.strictEqual(ctx.PlayerTileEvents.update('interior', -0.1, -16.1, 16), true);
assert.strictEqual(events[3].reason, 'area', 'a new map emits even when the coordinates are unchanged');
assert.strictEqual(ctx.PlayerTileEvents.update('interior', NaN, 0, 16), false);
assert.strictEqual(ctx.PlayerTileEvents.current(), null, 'missing/invalid player state resets the tracker');
assert.strictEqual(ctx.PlayerTileEvents.update('interior', 0, 0, 16), true);
assert.strictEqual(events[4].reason, 'initial');
assert.strictEqual(ctx.PlayerTileEvents.snapshot().subscriberErrors, 5, 'listener exceptions are isolated');
unsubscribeFailing();
unsubscribe();
assert.strictEqual(ctx.PlayerTileEvents.snapshot().subscribers, 0);

const TILE = 22; // Matches the pixel-to-tile conversion used by WildernessChunks.update.
const player = { x: 2.5 * TILE, y: 2.5 * TILE }; // Shared live player object read by the actual chunk owner.
let area = 'zone'; // Switches between the wilderness and interiors during the integration probe.
ctx.WildernessChunks.init({ getCurrentArea: () => area, isZoneArea: a => a === 'zone', player, TILE });
const zone = ctx.WildernessChunks.createZone({
  mapId: 'zone', scene: new Group(), cols: 64, rows: 64, focusCol: 2, focusRow: 2,
  buildChunk: () => ({}),
});
let neighborhoodCalls = 0; // Counts the stationary-world neighborhood scans avoided after arrival.
let unloadScanCalls = 0; // Counts resident-chunk sweeps avoided after arrival.
const enqueue = zone.enqueueNeighborhood.bind(zone);
const unload = zone.unloadOutside.bind(zone);
zone.enqueueNeighborhood = (...args) => { neighborhoodCalls++; return enqueue(...args); };
zone.unloadOutside = (...args) => { unloadScanCalls++; return unload(...args); };

const tracked = []; // Verifies the production chunk frame owner forwards events for every area.
ctx.PlayerTileEvents.subscribe(event => tracked.push(event));
for (let i = 0; i < 10; i++) ctx.WildernessChunks.update(0.2);
assert.strictEqual(neighborhoodCalls, 0, 'static chunk neighborhood is not scanned on unchanged frames');
assert.strictEqual(unloadScanCalls, 0, 'resident chunk set is not repeatedly swept while standing still');
assert.strictEqual(tracked.length, 1, 'the existing game frame owner emits the initial tile once');
player.x = 3.2 * TILE;
ctx.WildernessChunks.update(0.2);
assert.strictEqual(tracked.length, 2, 'one tile crossing emits one event');
assert.strictEqual(neighborhoodCalls, 0, 'crossing tiles within a chunk does not rebuild chunk candidates');
player.x = 18.1 * TILE;
ctx.WildernessChunks.update(0.2);
assert.strictEqual(neighborhoodCalls, 1, 'crossing a chunk boundary enqueues one neighborhood');
assert.strictEqual(unloadScanCalls, 1, 'crossing a chunk boundary sweeps old residency once');
area = 'farm';
ctx.WildernessChunks.update(0.2);
assert.strictEqual(tracked.at(-1).reason, 'area', 'the same frame owner continues events in non-wilderness areas');

// A previous allocation failure must retry after five seconds even when the
// player stands still; this path formerly relied on a per-frame neighborhood scan.
ctx.WildernessChunks.destroyZone('zone');
area = 'zone';
player.x = 2.5 * TILE;
player.y = 2.5 * TILE;
now = 0;
let attempts = 0; // Counts the first failed build and subsequent automatic retry.
const retryZone = ctx.WildernessChunks.createZone({
  mapId: 'zone', scene: new Group(), cols: 64, rows: 64, focusCol: 2, focusRow: 2,
  buildChunk({ cx, cz }) {
    if (cx === 0 && cz === 0) {
      attempts++;
      if (attempts === 1) throw new Error('synthetic first build failure');
    }
    return {};
  },
});
assert.strictEqual(attempts, 1);
ctx.WildernessChunks.update(0.02);
assert.strictEqual(attempts, 1, 'failed chunks respect their original five-second retry delay');
now = 5001;
ctx.WildernessChunks.update(0.2);
assert.strictEqual(attempts, 2, 'expired failed chunks are automatically retried without moving');
assert.ok(retryZone.loaded.has('0,0'));
assert.ok(listenerErrors.length >= 1, 'the intentionally failed chunk and listeners reported their errors');

console.log('Player tile event and stationary chunk integration tests passed.');
