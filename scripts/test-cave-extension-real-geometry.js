#!/usr/bin/env node
'use strict';

// Actual SDF-carved caverns, not only idealized paired-room fixtures.
// Measures whether real procedural shells have usable partitions and verifies
// that every installed rock wall physically separates a reachable side pocket.
const assert = require('node:assert/strict');
global.window = global;
require('../docs/js/cavern-sculptor.js');
require('../docs/js/cavern-generator.js');
require('../docs/js/cave-site-system.js');

const variants = [ // Small deterministic sampling, including the existing cave-boundary regression seed.
  'rim-integration-10', 'sense-cave-real-01', 'sense-cave-real-02',
  'sense-cave-real-03', 'sense-cave-real-04', 'sense-cave-real-05',
  'sense-cave-real-06', 'sense-cave-real-07',
];
const key = (col, row) => `${col},${row}`; // Used by the BFS and the cave wall cross-section check.
function reachable(start, floor, walls) {
  const seen = new Set(); // Tiles reachable through four-neighbor cave floors with all live rock walls blocked.
  if (!floor.has(start) || walls.has(start)) return seen;
  const queue = [start];
  seen.add(start);
  for (const here of queue) {
    const [col, row] = here.split(',').map(Number);
    for (const [dc, dr] of [[1,0],[-1,0],[0,1],[0,-1]]) {
      const next = key(col + dc, row + dr);
      if (floor.has(next) && !walls.has(next) && !seen.has(next)) { seen.add(next); queue.push(next); }
    }
  }
  return seen;
}
let eligible = 0; // Actual generated caverns in this sample that receive a rock partition.
let total = 0; // Walkable floor cells sampled, for useful failing assertion diagnostics.
for (const seed of variants) {
  const carved = CavernGenerator.generateCavernFloor(seed, { fast: true, cache: false });
  const map = { id: seed, ...carved, oreRocks: [] }; // Same floor/solid-rim/collider contract as ordinary den cave map data.
  map.colliders = carved.outerRimTiles;
  total += map.floor.length;
  const reserved = new Set(carved.outerRimTiles.map(cell => cell.join(','))); // Critical regression: these must not count as other floor features.
  const plan = { separator: null, ruinEntrance: null };
  const success = CaveSiteSystem.__test.installMineableSeparator(map, () => 0.43, reserved, plan);
  if (!success) continue;
  eligible++;
  const floor = new Set(map.floor.map(cell => cell.join(','))); // Walkable tiles generated by the real sculptor.
  const solid = new Set(plan.separator.cells.map(cell => key(cell.col, cell.row)));
  const start = key(map.exitCol, map.exitRow);
  const blockedReach = reachable(start, floor, solid);
  const openReach = reachable(start, floor, new Set());
  assert(openReach.size > blockedReach.size, seed + ': wall partitions cave floor');
  for (const cell of plan.separator.farKeys) {
    assert(!blockedReach.has(cell), seed + ': hidden chamber is actually unreachable before rock removal');
    assert(openReach.has(cell), seed + ': hidden chamber becomes reachable after all wall layers break');
  }
  assert(map.oreRocks.some(rock => rock.caveSeparator), seed + ': wall is represented by diggable ore tiles');
  assert(map.oreRocks.every(rock => floor.has(key(rock.col, rock.row))), seed + ': no wall is placed outside the carved cave floor');
}
console.log(`real carved cave annexes: ${eligible}/${variants.length} candidates; ${total} floor tiles checked`);
assert(eligible > 0, 'real cave generator must produce at least one viable breakable chamber across representative seeds');
