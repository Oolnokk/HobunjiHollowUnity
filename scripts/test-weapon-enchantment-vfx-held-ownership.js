'use strict';

// Regression: enchantment VFX must resolve the real equipment registry, and only
// the drawn player melee mesh may own emitters—even across an async mask decode.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');

const vfxSource = fs.readFileSync(path.join(__dirname, '../docs/js/combat/weapon-enchantment-vfx.js'), 'utf8');
const equipmentSource = fs.readFileSync(path.join(__dirname, '../docs/js/equipment-panel.js'), 'utf8');
const gameSource = fs.readFileSync(path.join(__dirname, '../docs/game.js'), 'utf8');
const combatInitBody = gameSource.split('window.Combat?.init({')[1]?.split('window.NearbyVolumeCollision?.init(')[0] || ''; // Live Combat injection inspected below.
assert(combatInitBody, 'game.js Combat.init production seam must be discoverable');
assert(!combatInitBody.includes('TOOL_ITEM_DEFS,'), 'this test must be updated if Combat gains an authoritative definitions registry');
assert(equipmentSource.includes('getToolDefinition: key => deps?.TOOL_ITEM_DEFS?.[key]'), 'EquipmentPanel must expose its live authored definitions');
assert(vfxSource.includes('window.EquipmentPanel?.getToolDefinition?.(key)'), 'enchantment scan must use the real equipment registry');

let now = 1000; // Test clock advanced below to drive the pre-render scheduler without browser timers.
let activeSlot = 'weapon'; // Set to ranged/hoe/none below to verify each slot's effect isolation.
let heldMode = 'tool'; // Set to none/item below to verify immediate emitter disposal on holster.
let registeredFrame = null; // Captures production scheduler callback invoked for each test frame.
const requests = []; // Image loaders held unresolved until the same-key mesh is replaced.

class Object3D {
  constructor() {
    this.children = []; this.parent = null; this.visible = true; this.userData = {};
    this.position = { x: 0, y: 0, z: 0 };
    this.scale = { x: 1, y: 1, z: 1 };
  }
  add(node) { node.parent?.remove?.(node); node.parent = this; this.children.push(node); }
  remove(node) { const i = this.children.indexOf(node); if (i !== -1) this.children.splice(i, 1); node.parent = null; }
  traverse(visitor) { visitor(this); for (const node of this.children) node.traverse?.(visitor); }
}
class DeferredImage {
  constructor() { this.naturalWidth = 2; this.naturalHeight = 2; }
  set src(value) { this.url = value; requests.push(this); }
}
const plane = () => Object.assign(new Object3D(), { isObject3D: true, geometry: { parameters: { width: 0.5, height: 0.5 } } }); // Each equipment rebuild gets a distinct planar sprite root.
const weapon = () => {
  const visual = new Object3D(); // Item-keyed mesh generated by game.js's makeToolPlaneMesh.
  visual.userData.itemKey = 'dagger_copper';
  visual.userData.toolPlane = plane();
  visual.add(visual.userData.toolPlane);
  return visual;
};
const holder = new Object3D(); // The live player tool holder, not an NPC or nearby scenery root.
let first = weapon(); // Original enchanted weapon mesh, invalidated while its mask still loads.
holder.add(first);
const definitions = { dagger_copper: { sprite: 'assets/dagger-source.png' } }; // The authored image path exists only on EquipmentPanel's definition registry.
const context = {
  window: {
    Combat: { deps: {
      getActiveTool: () => activeSlot,
      getHeldMode: () => heldMode,
      currentWeaponKey: () => 'dagger_copper',
      getGearInventory: () => ({}),
      getActiveScene: () => ({ traverse(visitor) { const enemy = weapon(); visitor(enemy); } }),
      // Deliberately NO TOOL_ITEM_DEFS: game.js does not inject it into Combat.
    } },
    EquipmentPanel: { getToolDefinition: key => definitions[key] || null },
    ProceduralHandAttachments: { gameDeps: { toolHolder: holder } },
    EnchantmentSystem: { PLANES: ['Ohthic'], planarCounts: () => ({ Ohthic: 1 }) },
    ColorFill: { rgbToHsv: () => ({ h: 0, s: 0 }), hueDistance: () => 0 },
    RuntimeFrameScheduler: { register(_id, callback) { registeredFrame = callback; } },
  },
  document: {
    baseURI: 'https://example.test/docs/',
    createElement() {
      return {
        width: 0, height: 0,
        getContext() {
          return {
            drawImage() {},
            getImageData() { return { width: 2, height: 2, data: Uint8ClampedArray.from([90, 132, 128, 255, ...Array(12).fill(0)]) }; },
          };
        },
      };
    },
  },
  THREE: { Group: Object3D }, // Emitter creation and removal use the real parent/child lifecycle.
  Image: DeferredImage, performance: { now: () => now }, URL,
  Uint32Array, Uint8ClampedArray, Map, Set, Object, Math, Number, Promise, console,
};
context.window.window = context.window;
vm.createContext(context);
vm.runInContext(vfxSource, context, { filename: 'weapon-enchantment-vfx.js' });
const api = context.window.WeaponEnchantmentVFX; // The actual production VFX module, rather than a test-reimplemented classifier.
const snapshot = () => api.debugSnapshot('dagger_copper'); // Mobile-facing debug values double as observable regression state.
const tick = at => { now = at; registeredFrame(at); }; // Runs the production update, including immediate equipment cleanup.

(async () => {
  assert(registeredFrame, 'VFX registers on the shared pre-render scheduler');
  assert.equal(snapshot().sourceSprite, 'assets/dagger-source.png', 'equipment registry supplies the metal-mask source');
  tick(1000);
  assert.equal(requests.length, 1, 'first weapon must start a real asynchronous metal scan');
  const second = weapon(); // Simulates rebuildToolMeshes() replacing the mesh while the source PNG is still decoding.
  holder.remove(first); holder.add(second);
  tick(1016);
  assert.equal(requests.length, 1, 'a shared in-flight image is decoded only once');
  requests[0].onload();
  await new Promise(resolve => setImmediate(resolve));
  assert.equal(snapshot().matchedMetalPixels, 1, 'the new weapon resolves the source PNG mask');
  assert.equal(snapshot().emitters, 1, 'only one emitter survives the pending-mask ownership change');
  assert.equal(first.userData.toolPlane.children.length, 0, 'an obsolete same-key mesh cannot receive a stale emitter');
  assert.equal(second.userData.toolPlane.children.length, 1, 'the current melee mesh receives the aura');

  // Rebuild the very same item again after its mask is cached: even without a
  // key change the old emitter must be detached on the next pre-render frame.
  const third = weapon(); // Simulates a second inventory/equipment presentation rebuild.
  holder.remove(second); holder.add(third);
  tick(1032);
  assert.equal(second.userData.toolPlane.children.length, 0, 'same-key rebuild immediately disposes the old emitter');
  await new Promise(resolve => setImmediate(resolve));
  assert.equal(snapshot().emitters, 1);
  assert.equal(third.userData.toolPlane.children.length, 1, 'cached-mask rebuild remounts on the actual live mesh');

  const ranged = new Object3D(); // An unenchanted ranged weapon can never inherit the melee item's particles.
  ranged.userData = { itemKey: 'bow', toolPlane: plane() };
  activeSlot = 'ranged'; holder.remove(third); holder.add(ranged);
  tick(1048);
  assert.equal(snapshot().emitters, 0, 'changing to ranged clears the emitter on that same frame');
  assert.equal(third.userData.toolPlane.children.length, 0, 'old melee aura group is actually detached');
  assert.equal(snapshot().heldVisualFound, false, 'ranged does not resolve the equipped melee visual');

  activeSlot = 'weapon'; holder.remove(ranged); holder.add(third);
  tick(1064);
  await new Promise(resolve => setImmediate(resolve));
  assert.equal(snapshot().emitters, 1, 'returning to melee restores its own effect');

  heldMode = 'none'; tick(1080);
  assert.equal(snapshot().emitters, 0, 'putting away a weapon clears its aura');
  heldMode = 'item'; tick(1096);
  assert.equal(snapshot().activeHeldWeaponKey, null, 'holding inventory items cannot spawn the effect');

  heldMode = 'tool'; activeSlot = 'hoe'; tick(1112);
  assert.equal(snapshot().emitters, 0, 'ordinary farming tools inherit no melee enchantments');

  activeSlot = 'weapon'; context.window.ProceduralHandAttachments.gameDeps.toolHolder = null;
  tick(1128);
  assert.equal(snapshot().heldVisualFound, false, 'without the player holder an enemy matching the weapon must never get an aura');
  assert.equal(snapshot().emitters, 0, 'missing owner fails closed');
  console.log('weapon-enchantment-vfx held ownership and scan races passed');
})().catch(error => { console.error(error); process.exitCode = 1; });
