'use strict';
// Isolated Tzatzul schema + unique-color + peck-hook smoke tests.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync('docs/js/tzatzul-registration.js', 'utf8');
const rigSource = fs.readFileSync('docs/js/flying-animal-rig.js', 'utf8');
const html = fs.readFileSync('docs/index.html', 'utf8');
const preset = JSON.parse(fs.readFileSync('docs/config/creatures/tzatzul-flying-rig.json', 'utf8'));
const calls = {};
const w = { Combat: { animalAttacks: { register(id, attack) { calls[id] = attack; } } }, THREE: {}, __farmLog() {} };
const ctx = { window: w, console, Math, String, Number, Array, Object, Promise, Date };
vm.runInNewContext(rigSource, ctx);
vm.runInNewContext(source, ctx);
const api = w.TzatzulRegistration;
assert.equal(preset.version, 1);
assert.equal(preset.talonCarry.birdScale, 2);
assert.equal(preset.perchSpline.beforePoints.length, 7);
assert.equal(preset.perchSpline.afterPoints.length, 7);
assert.deepEqual(Object.keys(preset.talonCarry.poses).sort(), ['animal','burden','humanoid']);
const palette = Array.from({length: 24}, (_, i) => api.identityFor('map_northern_cliffs', i));
assert.equal(new Set(palette.map(c => c.tintHex)).size, 24, 'all 24 sample map birds have distinguishable unique colors');
assert.equal(api.identityFor('map_northern_cliffs', 2).tintHex, palette[2].tintHex, 'reloaded birds retain identifying color');
assert.equal(api.identityFor('map_northern_cliffs', 2, palette[0]).tintHex, palette[0].tintHex, 'hatchlings match their mother');
const db = { grehlr: { attackDamage: 5, maxHealth: 100 } };
assert(api.register({ CREATURE_DB: db, TILE: 55 }));
assert.equal(db.tzatzul.isFlyingSpecies, true);
assert.equal(db['tzatzul-hatchling'].attacks[0], 'tzatzulPeck');
assert.equal(db['tzatzul-hatchling'].modelWidth, db.tzatzul.modelWidth * 3 / 8);
assert(Math.abs(db['tzatzul-hatchling'].modelWidth * db['tzatzul-hatchling'].spriteAspect / (db.tzatzul.modelWidth * (db.tzatzul.spriteAspect || 600 / 1375)) - 5 / 8) < 1e-10, 'native hatchling height is five eighths of adult height');
assert.equal(typeof calls.tzatzulPeck.update, 'function');
assert.match(html, /tzatzul-registration\.js\?v=/);
assert.match(fs.readFileSync('docs/js/wildlife-spawn.js','utf8'), /TzatzulRegistration\?\.register/);
assert.match(source, /SPRITES\.eyes, SPRITES\.blink\]\.map\(image\)/, 'the custom rig loads existing full-canvas eye and blink sprites');
assert.match(rigSource, /flyingAnimalEyeOverlay/, 'eye overlays are independent of the maternal body tint');
assert.match(rigSource, /eyePerched = .*perched\.geometry/, 'perched eyes inherit the authored shoulder spline');
assert.match(rigSource, /blinkShut \? eyeShutTexture : eyeOpenTexture/, 'blink swaps the overlay without replacing the bird body');
console.log('Tzatzul author export, registry, unique identities, inherited hatchling color and peck registration PASS.');
