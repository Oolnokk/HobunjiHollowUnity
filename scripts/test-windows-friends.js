'use strict';

// Lightweight tests of the optional Friends packaging; never need to install Electron.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { EventEmitter } = require('node:events');
const { createDesktopUpdates, FRIENDS_RELEASES_URL, RELEASES_URL } = require('../desktop/update-controller.cjs');
const { FEED_URL, APP_ID, PRODUCT_NAME, configureFriendsPackage, installerName, makeFriendsFeed } = require('./desktop-friends-build.js');

const root = path.resolve(__dirname, '..');
const original = JSON.parse(fs.readFileSync(path.join(root, 'desktop/package.json'), 'utf8')); // Ordinary main build must remain unchanged.
const friends = configureFriendsPackage(original, '0.2.123'); // Representative manual workflow run.

assert.equal(friends.productName, PRODUCT_NAME);
assert.equal(friends.build.productName, PRODUCT_NAME);
assert.equal(friends.build.appId, APP_ID);
assert.notEqual(original.build.appId, friends.build.appId);
assert.equal(friends.build.publish[0].provider, 'generic');
assert.equal(friends.build.publish[0].url, FEED_URL);
assert.equal(friends.build.win.artifactName, 'Hobunji-Hollow-Tester-Setup-' + '$' + '{version}.' + '$' + '{ext}');
assert.equal(original.build.publish[0].provider, 'github');
assert.equal(installerName('0.2.123'), 'Hobunji-Hollow-Tester-Setup-0.2.123.exe');
assert.throws(() => configureFriendsPackage(original, '../latest'), /Friends version/);
assert.throws(() => installerName('0.2.0'), /Friends version/);

// Test the two legacy/current installer references and preserve the checksum.
const yaml = [
  'version: 0.2.123',
  'files:',
  '  - url: Hobunji-Hollow-Tester-Setup-0.2.123.exe',
  '    sha512: fixturehash',
  '    size: 99',
  'path: Hobunji-Hollow-Tester-Setup-0.2.123.exe',
  'sha512: fixturehash',
  '',
].join('\n'); // The shape of the latest.yml generated by electron-builder NSIS.
const approved = makeFriendsFeed(yaml, '0.2.123');
const asset = 'https://github.com/Oolnokk/HobunjiHollowUnity/releases/download/friends-v0.2.123/Hobunji-Hollow-Tester-Setup-0.2.123.exe';
assert.ok(approved.includes('  - url: ' + asset));
assert.ok(approved.includes('path: ' + asset));
assert.equal((approved.match(/sha512: fixturehash/g) || []).length, 2);
assert.throws(() => makeFriendsFeed(yaml, '0.2.124'), /does not match/);
assert.throws(() => makeFriendsFeed(yaml.replace('path:', 'wrongfield:'), '0.2.123'), /exactly one/);
assert.throws(() => makeFriendsFeed(yaml.replace(/sha512:/g, 'nohash:'), '0.2.123'), /no file checksum/);

// Only an explicitly approved, main-based workflow can change the Friends feed.
const workflow = fs.readFileSync(path.join(root, '.github/workflows/windows-friends.yml'), 'utf8'); // Manual publication gate.
assert.match(workflow, /workflow_dispatch:/);
assert.ok(!/^\s{2}push:/m.test(workflow));
assert.match(workflow, /github.ref == 'refs\/heads\/main' && inputs.approval == 'PUBLISH'/);
assert.match(workflow, /--prerelease/);
assert.match(workflow, /friends-update-feed/);
assert.match(workflow, /desktop-friends-build.js feed/);
assert.notEqual(RELEASES_URL, FRIENDS_RELEASES_URL);

// The packaged product name chooses its status label, without changing download/install safety.
async function testFriendsController() {
  const updater = new EventEmitter(); // Fake update events require no network or installation.
  updater.checkForUpdates = async () => updater.emit('update-not-available');
  const controller = createDesktopUpdates({
    app: { getVersion: () => '0.2.123', getName: () => PRODUCT_NAME, isPackaged: true },
    BrowserWindow: class {},
    ipcMain: { handle() {} },
    shell: { openExternal() {} },
    autoUpdater: updater, getGameWindow: () => null,
    prepareRestart: async () => false,
  });
  controller.start({ autoCheck: false });
  assert.equal(updater.autoDownload, true);
  assert.equal(updater.autoInstallOnAppQuit, false);
  assert.equal(updater.allowPrerelease, false); // The generic approved manifest, not GitHub prereleases, is authoritative.
  await controller.checkNow();
  assert.equal(controller.snapshot().phase, 'current');
  assert.match(controller.snapshot().message, /approved Friends/);
  console.log('Windows Friends edition: independent feed, manual approval, immutable assets and auto-download OK');
}

testFriendsController().catch(error => { console.error(error); process.exitCode = 1; });
